/**
 * @file tests.h
 * @brief Тесты иерархии устройств умного дома — отдельный файл с тестами по заданию.
 * @details Каждая функция — группа проверок. Проверка сравнивает ожидаемый
 * результат с полученным и печатает `[OK]` или `[ОШИБКА]`; runAllTests() в конце
 * выводит итог. Описание тестов — на страницах @ref part1 и @ref part2.
 * @author Vareshka86
 * @date 2026-10-06
 * @version 0.2
 */

#ifndef TESTS_H
#define TESTS_H

/**
 * @brief Тест 1: создание объектов.
 * @details Создаёт лампу и термостат, проверяет их начальное состояние, изменение
 * температуры и режима термостата и счётчик устройств.
 */
void testCreation();

/**
 * @brief Тест 2: полиморфные вызовы.
 * @details Вызывает turnOn(), turnOff(), getStatus() через указатель на SmartDevice
 * и getPowerUsage() через ссылку на PoweredDevice; проверяет, что вызываются
 * версии лампы, а не базовых классов. Тот же указатель, направленный на термостат,
 * вызывает версии термостата; getPowerUsage() термостата — реализация по умолчанию.
 */
void testPolymorphism();

/**
 * @brief Тест 3: учёт энергии и статические члены.
 * @details Включает и выключает лампы, сдвигает модельное время, меняет яркость
 * включённой лампы и сверяет энергию каждой лампы и общий статический счётчик
 * getTotalEnergyConsumed() с расчётом «Вт × часы / 1000».
 */
void testEnergyAccounting();

/**
 * @brief Тест 4: неверные параметры и исключения.
 * @details Пустое имя, мощность 0 и меньше, яркость вне 1–100, пустой цвет, температура вне 5–35,
 * сдвиг времени не вперёд — везде ожидается std::invalid_argument, а объект и
 * счётчики остаются прежними.
 */
void testInvalidArguments();

/**
 * @brief Тест 5: виртуальный деструктор.
 * @details Создаёт лампу через `new`, включает её и удаляет через указатель на
 * SmartDevice. Проверяет, что вызвался деструктор лампы (энергия засчитана) и
 * счётчик устройств вернулся к прежнему значению.
 */
void testVirtualDestructor();

/**
 * @brief Тест 6: массив устройств через указатели на базовый класс.
 * @details Создаёт через 
ew две лампы и два термостата в массиве
 * SmartDevice* devices[4], в цикле включает их, сдвигает модельное время,
 * выключает и выводит статистику — getStatus() каждого устройства. Сверяет общий
 * счётчик энергии с расчётом и удаляет устройства через указатели на SmartDevice.
 */
void testDeviceArray();

/**
 * @brief Запускает все группы тестов и выводит итог.
 * @return true — все проверки пройдены.
 */
bool runAllTests();

#endif // TESTS_H
