/**
 * @file PoweredDevice.h
 * @brief Класс PoweredDevice — устройство с питанием и учётом энергии (промежуточный уровень).
 * @details Второй уровень иерархии: SmartDevice → **PoweredDevice** → конкретные
 * устройства. Добавляет номинальную мощность, виртуальную getPowerUsage() с
 * реализацией по умолчанию и учёт потреблённой энергии. Описание решения — на
 * странице @ref part1.
 * @author Vareshka86
 * @date 2026-10-05
 * @version 0.1
 */

#ifndef POWERED_DEVICE_H
#define POWERED_DEVICE_H

#include "SmartDevice.h"

#include <string>

/**
 * @brief Устройство с питанием: мощность, включение и выключение, учёт кВт·ч.
 * @details Реализует turnOn() и turnOff() из SmartDevice, но остаётся
 * **абстрактным**: getStatus() по-прежнему чисто виртуальная, её дают конкретные
 * устройства.
 *
 * **Учёт энергии.** Время в программе модельное: статическое поле clockHours_
 * (часы с запуска), его двигает статический метод advanceClock(). Пока
 * устройство включено, оно тратит getPowerUsage() ватт. Энергия засчитывается при
 * выключении (и при изменении параметров включённого устройства — см.
 * updateMeter()): кВт·ч = Вт × часы / 1000. Засчитанная энергия добавляется к
 * счётчику устройства и к общему статическому счётчику totalEnergyKWh_ всех
 * устройств — его возвращает getTotalEnergyConsumed().
 *
 * Инвариант: номинальная мощность — конечное число больше 0.
 */
class PoweredDevice : public SmartDevice
{
public:
    /**
     * @brief Включает устройство и запускает учёт энергии с текущего модельного часа.
     * @return true — устройство включилось; false — оно уже было включено.
     */
    bool turnOn() override;

    /**
     * @brief Выключает устройство и засчитывает энергию за время работы.
     * @return true — устройство выключилось; false — оно уже было выключено.
     */
    bool turnOff() override;

    /**
     * @brief Возвращает мощность, которую устройство тратит сейчас, в ваттах.
     * @details Виртуальная функция **с реализацией по умолчанию**: включённое
     * устройство тратит номинальную мощность, выключенное — 0. Наследники
     * переопределяют её: например, лампа тратит тем меньше, чем ниже яркость.
     * @return Мощность в ваттах (0, если устройство выключено).
     */
    virtual double getPowerUsage() const;

    /**
     * @brief Возвращает номинальную (наибольшую) мощность устройства.
     * @return Мощность в ваттах.
     */
    double getPowerConsumption() const;

    /**
     * @brief Возвращает энергию, засчитанную этому устройству.
     * @return Энергия в киловатт-часах.
     */
    double getEnergyConsumed() const;

    /**
     * @brief Возвращает энергию, засчитанную всем устройствам вместе.
     * @details Статическая функция: общий счётчик один на все устройства,
     * объект для вызова не нужен — `PoweredDevice::getTotalEnergyConsumed()`.
     * @return Энергия в киловатт-часах.
     */
    static double getTotalEnergyConsumed();

    /**
     * @brief Возвращает текущее модельное время.
     * @return Часы с запуска программы.
     */
    static double getClockHours();

    /**
     * @brief Сдвигает модельное время вперёд.
     * @details Включённые устройства «работают» это время; энергия за него
     * засчитается при их выключении.
     * @param hours На сколько часов сдвинуть время (больше 0).
     * @exception std::invalid_argument Если hours не больше 0 или не конечное число.
     */
    static void advanceClock(double hours);

protected:
    /**
     * @brief Конструктор для наследников: устройство с именем и мощностью, выключенное.
     * @param name             Имя устройства.
     * @param powerConsumption Номинальная мощность в ваттах (больше 0).
     * @exception std::invalid_argument Если имя пустое или мощность не больше 0.
     */
    PoweredDevice(const std::string& name, double powerConsumption);

    /**
     * @brief Конструктор копирования: копия с теми же параметрами и состоянием.
     * @details Копируется номинальная мощность и состояние «включено/выключено».
     * Энергия **не копируется**: копия — новое устройство и начинает со своих
     * 0 кВт·ч, иначе одна и та же энергия числилась бы дважды (у оригинала и у
     * копии), и сумма по устройствам разошлась бы с общим счётчиком. Если копия
     * включена, её интервал учёта начинается с текущего модельного часа.
     * @param other Копируемое устройство.
     */
    PoweredDevice(const PoweredDevice& other);

    /**
     * @brief Присваивание: берёт мощность и состояние из другого устройства.
     * @details Порядок действий важен. Сначала updateMeter() засчитывает энергию,
     * которую это устройство потратило до присваивания, **по его старым
     * параметрам** (наследники вызывают это присваивание до того, как меняют свои
     * поля). Затем копируются состояние и мощность, и интервал учёта начинается
     * заново с текущего часа. Накопленная энергия и имя остаются прежними — это
     * история и «личность» самого устройства, а не его параметры.
     * @param other Устройство, из которого берутся параметры.
     * @return Ссылка на это устройство.
     */
    PoweredDevice& operator=(const PoweredDevice& other);

    /**
     * @brief Засчитывает энергию, потраченную с начала текущего интервала.
     * @details Если устройство включено, добавляет getPowerUsage() × (время
     * сейчас − начало интервала) / 1000 кВт·ч к счётчику устройства и к общему
     * счётчику и начинает новый интервал с текущего часа. Наследники вызывают
     * этот метод **перед** изменением параметров, влияющих на мощность (например,
     * яркости): энергия до изменения считается по старой мощности, после — по новой.
     *
     * getPowerUsage() здесь вызывается виртуально, поэтому берётся мощность
     * конкретного устройства (лампы, термостата), а не реализация по умолчанию.
     */
    void updateMeter();

private:
    static double totalEnergyKWh_; ///< Энергия, засчитанная всем устройствам, кВт·ч
    static double clockHours_;     ///< Модельное время, часы с запуска программы

    double powerConsumption_; ///< Номинальная мощность, Вт (больше 0)
    double energyKWh_;        ///< Энергия, засчитанная этому устройству, кВт·ч
    double meterStartHours_;  ///< Модельный час начала текущего интервала учёта (когда включено)
};

#endif // POWERED_DEVICE_H
