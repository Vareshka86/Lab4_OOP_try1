#ifndef SMART_DEVICE_H
#define SMART_DEVICE_H

#include <string>

/**
 * @brief Абстрактное устройство умного дома: имя и состояние «включено/выключено».
 * @details Класс **абстрактный**: в нём три чисто виртуальные функции — turnOn(),
 * turnOff() и getStatus(). Создать объект SmartDevice нельзя; создаются только
 * объекты конкретных наследников, а работать с ними можно через указатель или
 * ссылку на SmartDevice — это полиморфизм.
 *
 * Деструктор виртуальный: без этого `delete` через указатель на SmartDevice
 * вызвал бы только деструктор базового класса (неопределённое поведение).
 *
 * Инвариант: имя не пустое.
 *
 * Статическое поле existingCount_ хранит, сколько устройств существует сейчас.
 */
class SmartDevice
{
public:
    /**
     * @brief Виртуальный деструктор: уменьшает счётчик существующих устройств.
     */
    virtual ~SmartDevice();

    /**
     * @brief Копирование до части 4 запрещено.
     * @details Копия устройства должна правильно учитывать состояние и счётчик
     * энергии; конструктор копирования с таким учётом появится в части 4
     * (версия v1.0). До этого копирование отключено (`= delete`), чтобы
     * компилятор не создал копирование «по умолчанию» с неверным учётом.
     */
    SmartDevice(const SmartDevice&) = delete;

    /**
     * @brief Присваивание до части 4 запрещено (см. конструктор копирования).
     * @return Ссылка на этот объект — функция удалена (`= delete`) и не вызывается.
     */
    SmartDevice& operator=(const SmartDevice&) = delete;

    /**
     * @brief Включает устройство.
     * @details Чисто виртуальная функция: у SmartDevice нет реализации,
     * её обязаны дать наследники.
     * @return true — устройство включилось; false — оно уже было включено.
     */
    virtual bool turnOn() = 0;

    /**
     * @brief Выключает устройство.
     * @return true — устройство выключилось; false — оно уже было выключено.
     */
    virtual bool turnOff() = 0;

    /**
     * @brief Возвращает описание состояния устройства одной строкой.
     * @return Например «Лампа «Кухня»: включена, яркость 80 %, …».
     */
    virtual std::string getStatus() const = 0;

    /**
     * @brief Возвращает имя устройства.
     * @return Константная ссылка на имя.
     */
    const std::string& getName() const;

    /**
     * @brief Проверяет, включено ли устройство.
     * @return true — включено.
     */
    bool isOn() const;

    /**
     * @brief Возвращает число существующих сейчас устройств.
     * @details Статический метод: вызывается через имя класса —
     * `SmartDevice::getExistingCount()`.
     * @return Сколько объектов-устройств создано и ещё не уничтожено.
     */
    static int getExistingCount();

protected:
    /**
     * @brief Конструктор для наследников: устройство с именем, выключенное.
     * @details Защищённый (`protected`): вызывать его могут только конструкторы
     * наследников — сам SmartDevice абстрактный.
     * @param name Имя устройства, например «Кухня».
     * @exception std::invalid_argument Если имя пустое.
     */
    explicit SmartDevice(const std::string& name);

    /**
     * @brief Меняет состояние «включено/выключено».
     * @details Защищённый метод: состояние меняют только turnOn() и turnOff()
     * наследников, снаружи класса — нельзя.
     * @param on true — включено, false — выключено.
     */
    void setOn(bool on);

private:
    static int existingCount_; ///< Сколько устройств существует сейчас (общее для всех)

    std::string name_; ///< Имя устройства (не пустое)
    bool isOn_;        ///< true — устройство включено
};

#endif // SMART_DEVICE_H
