#ifndef I_SENSOR_H
#define I_SENSOR_H

/**
 * @brief Датчик: умеет сообщать текущее напряжение.
 * @details Интерфейс не связан с иерархией SmartDevice: датчиком может быть
 * и не устройство с питанием. Поэтому SmartOutlet наследует его отдельно,
 * вторым базовым классом.
 *
 * Деструктор виртуальный: объект можно удалить и через указатель на ISensor,
 * тогда вызовутся деструкторы всех его классов.
 */
class ISensor
{
public:
    /**
     * @brief Виртуальный деструктор.
     * @details `= default` — тело пустое, его создаёт компилятор; главное здесь
     * слово `virtual`.
     */
    virtual ~ISensor() = default;

    /**
     * @brief Возвращает текущее напряжение, которое измеряет датчик.
     * @details Чисто виртуальная функция: реализацию дают классы-датчики.
     * @return Напряжение в вольтах.
     */
    virtual double getCurrentVoltage() const = 0;
};

#endif // I_SENSOR_H
